/** نرمال‌سازیِ سبکِ مقایسه — ی/کِ عربی، اِعراب، نیم‌فاصله، فاصله‌ها */
function normalizeForMatch(raw: string): string {
  let t = raw.trim()
  t = t.split("\u064A").join("\u06CC") // ي → ی
  t = t.split("\u0643").join("\u06A9") // ك → ک
  t = t.replace(/[\u064B-\u065F\u0670]/g, "") // اِعراب
  t = t.split("\u200C").join("") // نیم‌فاصله
  return t.replace(/\s+/g, " ").trim()
}

/**
 * جایگزین‌های تاریخی — «آیتم‌ها» فقط وقتی برچسبِ ناوبریِ ایستاده است
 * (عینِ خودش، بعد از trim) به «کیف» می‌رود؛ عنوانِ بخش («کیف و آیتم‌ها»)
 * و جمله‌هایِ لور دست‌نخورده می‌مانند (قاعده‌ی ۲ و ۴ در سردرِ فایل).
 */
const LEGACY_LABELS: ReadonlyArray<readonly [string, string]> = [
  ["فمبویِ روح‌بسته", TERM.character.label],
  ["وقت‌گذرانی", TERM.interact.label],
  ["پیشخوان", TERM.home.label],
  ["شهرِ گروهی", TERM.groupWorld.label],
  ["آیتم‌ها", TERM.inventory.label], // فقط برچسبِ ایستاده — قاعده‌ی ۴
  ["راهنمای من", TERM.nextStep.label],
]

/**
 * برچسبِ تاریخی → برچسبِ قاعده‌مند. فقط برای «برچسب‌های ناوبری/دکمه» به کار
 * می‌رود (مهاجرتِ فازهای بعدیِ V16)؛ نثرِ لور و بدنه‌ی کدکس معاف‌اند (قاعده‌ی ۲)
 * و هرگز نباید روی متنِ بلند اعمال شود — ورودیِ این تابع «برچسب» است، نه جمله.
 * رشته‌ی ناشناخته عیناً برمی‌گردد (بدونِ حدس).
 */
export function canonicalizeLabel(s: string): string {
  const key = normalizeForMatch(s)
  for (const [legacy, canonical] of LEGACY_LABELS) {
    if (key === normalizeForMatch(legacy)) return canonical
  }
  return s
}
