// هر طبع یک قوسِ اختصاصیِ ۵-فصلی دارد: خاستگاه → اتفاقِ اول → انتخابِ معنادار
// → آشکارسازی → نقطه‌ی عطف. انتخاب‌ها پیامدِ ماندگار دارند: اعتماد/پیوند/
// روحیه/XP و یک ردیفِ روایی در CharacterLog (نوعِ story) که «مرورِ خاطره»
// همان‌ها را زنده نگه می‌دارد.
//
// قواعد (مأموریت §4):
//   · هیچ قصه‌ای «غریبه‌ای مرموز با گذشته‌ای تیره» نیست — هشت لحنِ متفاوت:
//     گرم/معمایی/مغرورانه/خنده‌دار/آرام/حصاری/آدرنالینی/ذهنی.
//   · هر انتخاب باید پیامدِ واقعی داشته باشد؛ وعده‌ی بی‌پیامد ممنوع.
//   · سدها صادق و دیده‌شونده‌اند: trust [0,10,25,40,60] + level [1,2,4,6,8].
//   · فصلِ آخر پاداشِ پایان می‌دهد (عنوانِ «راویِ پیمان» + جلا) — در موتور.

export interface StoryChoice {
  /** برچسبِ دکمه */
  label: string
  /** یک خط — چه چیزی در بازی می‌آید/مهم می‌شود */
  hint: string
  /** دلتای اعتماد (0..8) */
  trust: number
  /** دلتای پیوند (اختیاری) */
  bond?: number
  /** دلتای روحیه (اختیاری) */
  spirit?: number
  /** XP فمبوی روی مسیرِ spirit (اختیاری) */
  xp?: number
  /** دلتای سکه‌ی بازیکن (اختیاری، نادر) */
  money?: number
  /** روایتِ پیامد — در CharacterLog(type=story) می‌نشیند */
  outcome: string
}

export interface StoryChapter {
  id: string
  title: string
  icon: string
  /** ۲-۳ بندِ روایی */
  text: string[]
  choices: StoryChoice[]
  req: { trust: number; level: number }
}

export interface StoryDef {
  /** = کلیدِ طبع */
  key: string
  emoji: string
  title: string
  arcSummary: string
  chapters: StoryChapter[]
}

// ─── پله‌های اعتماد (0..100) — داستان با این‌ها جلو می‌رود ─────────────────────

export const TRUST_TIERS: { min: number; label: string; emoji: string }[] = [
  { min: 0, label: "غریبه", emoji: "👀" },
  { min: 15, label: "آشنا", emoji: "🤝" },
  { min: 30, label: "رفیق", emoji: "🫂" },
  { min: 50, label: "یارِ خاص", emoji: "💞" },
  { min: 70, label: "جانِ جان", emoji: "👑" },
]

export function trustTierOf(trust: number): { min: number; label: string; emoji: string } {
  let hit = TRUST_TIERS[0]!
  for (const t of TRUST_TIERS) if (trust >= t.min) hit = t
  return hit
}

export function nextTrustTier(trust: number): { min: number; label: string; emoji: string } | null {
  for (const t of TRUST_TIERS) if (trust < t.min) return t
  return null
}

