export const STORY_MAP: Map<string, StoryDef> = new Map(STORIES.map((s) => [s.key, s]))

export function getStory(personaKey: string): StoryDef | null {
  return STORY_MAP.get(personaKey) ?? null
}

export const STORY_TOTAL_CHAPTERS = 5

// ─── اعتبارسنجیِ بارگذاری (همان الگویِ کلاس‌ها) ────────────────────────────────

function validateStories(): void {
  if (STORIES.length !== 8) throw new Error("داستان‌ها: باید دقیقاً ۸ قوس باشد (یکی به‌ازای هر طبع)")
  const personas = new Set(["sunny", "shadow", "noble", "sly", "gentle", "prickly", "storm", "mind"])
  for (const s of STORIES) {
    if (!personas.has(s.key)) throw new Error(`داستانِ ${s.key}: طبعِ ناشناخته`)
    personas.delete(s.key)
    if (s.chapters.length !== STORY_TOTAL_CHAPTERS) throw new Error(`داستانِ ${s.key}: باید ۵ فصل باشد`)
    const seenIds = new Set<string>()
    for (let i = 0; i < s.chapters.length; i++) {
      const c = s.chapters[i]!
      if (!c.id || seenIds.has(c.id)) throw new Error(`داستانِ ${s.key}: شناسه‌ی فصلِ تکراری/خالی`)
      seenIds.add(c.id)
      if (c.text.length < 2 || c.text.some((t) => !t || t.length < 20)) throw new Error(`فصلِ ${c.id}: متنِ ناقص`)
      if (c.choices.length < 2 || c.choices.length > 3) throw new Error(`فصلِ ${c.id}: ۲ یا ۳ انتخاب لازم است`)
      for (const ch of c.choices) {
        if (!ch.label || !ch.hint || !ch.outcome) throw new Error(`فصلِ ${c.id}: انتخابِ ناقص`)
        if (ch.trust < 0 || ch.trust > 8) throw new Error(`فصلِ ${c.id}: دلتای اعتماد باید ۰..۸ باشد`)
        if (ch.money !== undefined && Math.abs(ch.money) > 400) throw new Error(`فصلِ ${c.id}: پولِ داستان باید کوچک باشد`)
        if (ch.xp !== undefined && (ch.xp < 0 || ch.xp > 60)) throw new Error(`فصلِ ${c.id}: XPِ داستان باید ۰..۶۰ باشد`)
      }
      // سدها صعودی و منطقی: اعتماد 0/10/25/40/60 + سطح 1/2/4/6/8
      const expectedTrust = [0, 10, 25, 40, 60][i]!
      const expectedLevel = [1, 2, 4, 6, 8][i]!
      if (c.req.trust !== expectedTrust || c.req.level !== expectedLevel)
        throw new Error(`فصلِ ${c.id}: سدها باید trust=${expectedTrust}, level=${expectedLevel} باشند`)
    }
  }
  if (personas.size > 0) throw new Error(`داستانِ برایِ طبع‌هایِ ${[...personas].join(",")} نیست`)
}

validateStories()
