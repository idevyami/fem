// ─── اعتبارسنجیِ بارگذاری (همان الگویِ validateClasses) ─────────────────────────

const VOICE_KINDS: InteractKindKey[] = ["comfort", "praise", "talk", "treat", "restTogether", "practice", "celebrate", "gift", "memory"]

function validatePersonas(): void {
  const seen = new Set<string>()
  for (const p of PERSONAS) {
    if (!p.key || seen.has(p.key)) throw new Error(`طبعِ تکراری/خالی: ${p.key}`)
    seen.add(p.key)
    if (!p.name || !p.tagline) throw new Error(`طبعِ ${p.key}: نام/تگ‌لاین خالی`)
    if (p.traits.length !== 3 || p.traits.some((t) => !t)) throw new Error(`طبعِ ${p.key}: دقیقاً ۳ صفت لازم است`)
    for (const k of VOICE_KINDS) {
      const line = p.voice[k]
      if (!line || !line.includes("{name}")) throw new Error(`طبعِ ${p.key}: صدای ${k} خالی یا بدونِ {name}`)
    }
    if (p.talents.length < 2 || p.flaws.length < 1) throw new Error(`طبعِ ${p.key}: استخرِ استعداد/ضعف خیلی کوچک است`)
    // ارجاع‌های talents/flaws در talents.ts اعتبارسنجی می‌شوند (validateTalents)
  }
}

