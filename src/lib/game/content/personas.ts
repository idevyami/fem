// FEMBOY WAR — V19: طبع‌ها (personality archetypes) — «شخصیتِ بازآفرینی‌شده»
//
// طبع بُعدِ «چطور رفتار می‌کند و حرف می‌زند» است؛ کلاس بُعدِ «چه‌کاره است».
// دو فمبوی با یک کلاس می‌توانند کاملاً متفاوت باشند چون طبع‌شان فرق دارد.
//
// قواعد (مأموریت §3.2):
//   ۱. طبع و کلاس دو بُعدِ مستقل‌اند؛ هیچ‌کدام دیگری را بازنویسی نمی‌کند.
//   ۲. طبع روی روایت/گفتار اثر می‌گذارد، نه روی قواعدِ مرجعِ بازی (آن کارِ
//      استعداد/ضعف است که در talents.ts آمده).
//   ۳. طبع در طولِ درخواست‌ها تغییر نمی‌کند — personaKey روی رکورد می‌نشیند.
//   ۴. خطوطِ صدا قطعی‌اند و با الگویِ.seed روزانه‌ی موجود (mulberry32+seedFrom)
//      انتخاب می‌شوند — همان روز، همان لهجه.
//   ۵. مدلِ عمیق (ریسک‌پذیری/انگیزه/مرزها) پشتِ صحنه می‌ماند؛ بازیکن تفسیرِ
//      خوانا می‌بیند («مرموز، محتاط و عاشقِ کشفِ رازها»).

export type InteractKindKey =
  | "comfort"
  | "praise"
  | "talk"
  | "treat"
  | "restTogether"
  | "practice"
  | "celebrate"
  | "gift"
  | "memory"

export interface PersonaDef {
  key: string
  emoji: string
  /** نامِ طبع — یک واژه */
  name: string
  /** تفسیرِ خوانا برای بازیکن (یک خط) */
  tagline: string
  /** سه صفتِ کوتاه */
  traits: string[]
  /** صدای طبع به‌ازای هر نوعِ تعامل — {name} با اسمِ فمبوی جایگزین می‌شود */
  voice: Record<InteractKindKey, string>
  /** استعدادهایی که این طبع به سمتشان می‌رود (کلیدهای talents.ts) */
  talents: string[]
  /** ضعف‌هایی که این طبع درگیرشان می‌شود (کلیدهای talents.ts) */
  flaws: string[]
}

